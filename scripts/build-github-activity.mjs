import { execFileSync } from "node:child_process"
import { writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const rootDir = join(dirname(fileURLToPath(import.meta.url)), "..")
const outputPath = join(rootDir, "src", "data", "githubActivity.ts")

const LOGIN = "rafaelmedian"
// Half a year of dots. Wide enough that a quiet fortnight reads as a gap rather
// than as the whole picture, narrow enough to sit in a hover card without
// scrolling.
const MONTHS = 6

const QUERY = `
query($login: String!, $from: DateTime!, $to: DateTime!) {
  user(login: $login) {
    contributionsCollection(from: $from, to: $to) {
      contributionCalendar {
        totalContributions
        weeks { contributionDays { date contributionCount } }
      }
    }
  }
}`

const to = new Date()
const from = new Date(to)
from.setUTCMonth(from.getUTCMonth() - MONTHS)

// `gh` rather than a raw fetch with a hand-rolled token: the contribution
// calendar is only available through the authenticated GraphQL API, and `gh`
// already holds the credentials this machine is signed in with. Nothing about
// this runs in CI -- the output below is committed, exactly like the résumé.
const raw = execFileSync(
  "gh",
  [
    "api", "graphql",
    "-f", `query=${QUERY}`,
    "-f", `login=${LOGIN}`,
    "-f", `from=${from.toISOString()}`,
    "-f", `to=${to.toISOString()}`,
    "--jq", ".data.user.contributionsCollection.contributionCalendar",
  ],
  { cwd: rootDir, encoding: "utf8", maxBuffer: 16 * 1024 * 1024 },
)

const calendar = JSON.parse(raw)

// GitHub's first and last weeks are partial. Padding them out to seven keeps the
// grid rectangular; a null day is a cell the window does not cover, which the
// card draws as nothing rather than as a quiet day.
const weeks = calendar.weeks.map((week, index) => {
  const days = week.contributionDays.map((day) => ({ date: day.date, count: day.contributionCount }))
  const padding = Array.from({ length: 7 - days.length }, () => null)
  return index === 0 ? [...padding, ...days] : [...days, ...padding]
})

const counts = weeks
  .flat()
  .map((day) => day?.count ?? 0)
  .filter((count) => count > 0)
  .sort((a, b) => a - b)

const max = counts.at(-1) ?? 0

// Quartiles of the busy days rather than fractions of the busiest one. Scaling
// to the maximum sounds right and looks wrong: one 102-commit day drags every
// ordinary 8-commit day into the palest band and the graph goes flat. Splitting
// the days that had any work at all into four equal groups is what GitHub does,
// and it is what makes a normal week legible next to an exceptional one.
const quartile = (fraction) => counts[Math.min(counts.length - 1, Math.floor(counts.length * fraction))] ?? 0
const thresholds = [quartile(0.25), quartile(0.5), quartile(0.75)]

const file = `// GENERATED by scripts/build-github-activity.mjs -- do not edit by hand.
//
// @${LOGIN}'s contribution calendar, fetched once and committed rather than
// requested at run time or at build time. The profile-wide graph is only
// available through GitHub's authenticated GraphQL API, so a live read would
// mean a token in CI; this is the same deal the résumé PDF makes, and it goes
// stale the same way. Re-run the script and commit the result.
//
// Fetched ${new Date().toISOString().slice(0, 10)}.

/** A day in the calendar, or null for a cell the window does not cover. */
export type ContributionDay = { date: string; count: number } | null

export type ContributionCalendar = {
  login: string
  /** UTC \`YYYY-MM-DD\` the data was fetched, so staleness is visible in the diff. */
  fetchedOn: string
  total: number
  /** The busiest day in the window. */
  max: number
  /** Upper bound of shading bands 1, 2, and 3; anything above is band 4. */
  thresholds: [number, number, number]
  /** Weeks oldest-first, each seven days Sunday-first. */
  weeks: ContributionDay[][]
}

export const contributionCalendar: ContributionCalendar = {
  login: ${JSON.stringify(LOGIN)},
  fetchedOn: ${JSON.stringify(new Date().toISOString().slice(0, 10))},
  total: ${calendar.totalContributions},
  max: ${max},
  thresholds: [${thresholds.join(", ")}],
  weeks: [
${weeks
  .map(
    (week) =>
      `    [${week
        .map((day) => (day === null ? "null" : `{ date: "${day.date}", count: ${day.count} }`))
        .join(", ")}],`,
  )
  .join("\n")}
  ],
}
`

writeFileSync(outputPath, file)
console.log(
  `Wrote ${outputPath} (${calendar.totalContributions} contributions across ${weeks.length} weeks, busiest day ${max}, bands at ${thresholds.join("/")})`,
)
