// Build development preview media from an explicitly supplied local recording.
// Usage: node scripts/build-about-intro-placeholder.mjs <original.mp4> [vertical-crop-position]
import { spawnSync, execFileSync } from 'node:child_process'
import { copyFile, mkdtemp, rm, stat, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import ffmpeg from 'ffmpeg-static'

const root = fileURLToPath(new URL('../', import.meta.url))
if (!process.argv[2]) throw new Error('Supply a local recording: node scripts/build-about-intro-placeholder.mjs <original.mp4>')
const input = resolve(process.argv[2])
const cropPosition = Number(process.argv[3] ?? 0.5)
if (!Number.isFinite(cropPosition) || cropPosition < 0 || cropPosition > 1) {
  throw new Error('Vertical crop position must be between 0 (top) and 1 (bottom)')
}
const temporary = await mkdtemp(join(tmpdir(), 'about-speaking-'))
const probe = file => {
  const result = spawnSync(ffmpeg, ['-hide_banner', '-i', file], { encoding: 'utf8' })
  if (result.error) throw result.error
  const match = result.stderr.match(/Duration:\s+(\d+):(\d+):(\d+(?:\.\d+)?)/)
  if (!match || !/Stream #.*Video:/.test(result.stderr)) throw new Error('Source must be a readable video')
  return { duration: Number(match[1]) * 3600 + Number(match[2]) * 60 + Number(match[3]), hasAudio: /Stream #.*Audio:/.test(result.stderr) }
}
try {
  const source = probe(input)
  const output = join(root, 'tests/fixtures/about-intro')
  const run = args => execFileSync(ffmpeg, ['-y', ...args], { stdio: 'ignore', timeout: 120_000 })
  // Reserve room for audio and container overhead within the 5 MB budget.
  const videoKbps = Math.min(650, Math.floor(4_700_000 * 8 / source.duration / 1000 - (source.hasAudio ? 96 : 0)))
  if (videoKbps < 150) throw new Error('Recording is too long for the preview budget')
  const crop = `crop='min(iw,ih)':'min(iw,ih)':(iw-ow)/2:(ih-oh)*${cropPosition}`
  run(['-i', input, '-map', '0:v:0', '-map', '0:a?', '-vf', `${crop},scale='min(iw,624)':-2,fps=30`,
    '-c:v', 'libx264', '-crf', '25', '-preset', 'slow', '-pix_fmt', 'yuv420p',
    '-maxrate', `${videoKbps}k`, '-bufsize', `${videoKbps * 2}k`, '-c:a', 'aac', '-b:a', '96k',
    '-movflags', '+faststart', join(temporary, 'recording.mp4')])
  // Keep the largest preview that fits the existing 150KB request budget.
  for (const size of [224, 192, 160, 144]) {
    run(['-t', '2', '-i', join(temporary, 'recording.mp4'), '-filter_complex',
      `[0:v]fps=8,scale=${size}:${size}:flags=lanczos,split[a][b];[a]palettegen=max_colors=32[p];[b][p]paletteuse=dither=bayer:bayer_scale=5`,
      '-loop', '0', join(temporary, 'teaser.gif')])
    if ((await stat(join(temporary, 'teaser.gif'))).size < 150_000) {
      console.log(`Teaser: ${size}px`)
      break
    }
  }
  run(['-i', join(temporary, 'recording.mp4'), '-vf', 'scale=360:360:flags=lanczos',
    '-frames:v', '1', '-quality', '80', join(temporary, 'poster.webp')])
  const { duration, hasAudio } = probe(join(temporary, 'recording.mp4'))
  const transcript = hasAudio ? 'Uploaded preview recording; speech captions have not been supplied.' : 'Silent uploaded recording for testing the introduction player.'
  await writeFile(join(temporary, 'captions.vtt'), `WEBVTT\n\n00:00.000 --> 00:02.000\n${hasAudio ? '[Preview recording]' : '[Silent recording]'}\n`)
  if ((await stat(join(temporary, 'teaser.gif'))).size >= 150_000) throw new Error('Teaser exceeds 150 KB')
  if ((await stat(join(temporary, 'recording.mp4'))).size >= 5_000_000) throw new Error('Recording exceeds 5 MB')
  const base = '/tests/fixtures/about-intro'
  const manifest = { placeholder: true, duration, transcript, assets: {
    recording: `${base}/recording.mp4`, teaser: `${base}/teaser.gif`, poster: `${base}/poster.webp`, captions: `${base}/captions.vtt`,
  } }
  for (const file of ['recording.mp4', 'teaser.gif', 'poster.webp', 'captions.vtt']) {
    await copyFile(join(temporary, file), join(output, file))
    console.log(`${file}: ${(await stat(join(output, file))).size} bytes`)
  }
  await writeFile(join(root, 'src/data/aboutIntroPreview.ts'), `// Generated by scripts/build-about-intro-placeholder.mjs.\nimport type { AboutIntroMedia } from "./aboutIntro"\n\nexport const aboutIntroPreview: AboutIntroMedia = ${JSON.stringify(manifest, null, 2)}\n`)
  console.log(`Duration: ${duration}s; audio: ${hasAudio}`)
} finally {
  await rm(temporary, { recursive: true, force: true })
}
