// AVIF siblings for the project previews that already have WebP widths (see
// generate-preview-variants.mjs and src/lib/media.ts). A <picture> offers them
// first; a browser without AVIF keeps the WebP srcset it had before.
//
// Product screenshots carry small UI text, so no fixed quality is trusted. Each
// source tries rising qualities at full size and keeps the lowest whose decode
// stays within MIN_SSIM of the shipped WebP, then encodes every width at it.
// A source that cannot get at least MIN_SAVING smaller gets no AVIF at all.
// The result is src/data/avifSources.ts, which media.ts reads: a source is
// only offered as AVIF once every one of its widths exists.
//
// Encodes from the full-size WebP (the original capture), never from a
// variant. Rerunning skips sources already in the manifest whose files exist;
// pass --force to re-encode.
import ffmpegPath from "ffmpeg-static"
import sharp from "sharp"
import { access, mkdtemp, readFile, readdir, rm, stat, writeFile } from "node:fs/promises"
import { spawn } from "node:child_process"
import { fileURLToPath } from "node:url"
import os from "node:os"
import path from "node:path"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const projects = path.join(root, "public/Projects")
const manifestPath = path.join(root, "src/data/avifSources.ts")
const manifestHeader = "// Generated by scripts/generate-avif-variants.mjs: each source with AVIF\n" +
  "// siblings at every WebP width, and the quality it was encoded at.\n" +
  "export const avifSources: Readonly<Record<string, number>> = "
const qualities = [50, 56, 62, 68, 74]
const MIN_SSIM = 0.993
const MIN_SAVING = 0.15
const force = process.argv.includes("--force")

sharp.concurrency(2)

const exists = file => access(file).then(() => true, () => false)

function ssim(reference, candidate) {
  return new Promise((resolve, reject) => {
    const ffmpeg = spawn(ffmpegPath, ["-i", reference, "-i", candidate, "-lavfi", "ssim", "-f", "null", "-"])
    let log = ""
    ffmpeg.stderr.on("data", chunk => { log += chunk })
    ffmpeg.on("error", reject)
    ffmpeg.on("exit", () => {
      const all = log.match(/All:([\d.]+)/)
      if (all) resolve(Number(all[1]))
      else reject(new Error(`No SSIM for ${candidate}`))
    })
  })
}

async function variantsOf(stem) {
  const name = path.basename(stem)
  const pattern = new RegExp(`^${name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}-(\\d+)w\\.webp$`)
  const widths = []
  for (const file of await readdir(projects)) {
    const match = file.match(pattern)
    if (match) widths.push(Number(match[1]))
  }
  return widths.sort((a, b) => a - b)
}

async function chooseQuality(source, scratch) {
  const original = await stat(source)
  const reference = path.join(scratch, "reference.png")
  await sharp(source).png().toFile(reference)
  for (const quality of qualities) {
    const encoded = await sharp(source).avif({ quality, effort: 6 }).toBuffer()
    if (encoded.length > original.size * (1 - MIN_SAVING)) return null
    const decoded = path.join(scratch, `q${quality}.png`)
    await sharp(encoded).png().toFile(decoded)
    const score = await ssim(reference, decoded)
    if (score >= MIN_SSIM) return { quality, score, bytes: encoded.length, original: original.size }
  }
  return null
}

const readManifest = async () => {
  const text = await readFile(manifestPath, "utf8").catch(() => "")
  return text ? JSON.parse(text.slice(text.indexOf("{"))) : {}
}
const manifest = force ? {} : await readManifest()
const files = await readdir(projects)
const sources = files
  .filter(file => /\.webp$/.test(file) && !/-\d+w\.webp$/.test(file) && files.includes(file.replace(/\.webp$/, "-96w.webp")))
  .sort()

let saved = 0
let skipped = 0
async function encodeSource(file) {
  const source = path.join(projects, file)
  const stem = source.slice(0, -".webp".length)
  const key = `/Projects/${file}`
  const { width: intrinsic } = await sharp(source).metadata()
  const widths = (await variantsOf(stem)).filter(width => width < intrinsic)
  const outputs = [`${stem}.avif`, ...widths.map(width => `${stem}-${width}w.avif`)]
  if (manifest[key] && (await Promise.all(outputs.map(exists))).every(Boolean)) return

  const scratch = await mkdtemp(path.join(os.tmpdir(), "avif-"))
  try {
    const chosen = await chooseQuality(source, scratch)
    if (!chosen) {
      delete manifest[key]
      skipped++
      console.log(`skip ${file}: no quality met SSIM ${MIN_SSIM} at ${MIN_SAVING * 100}% smaller`)
      return
    }
    await sharp(source).avif({ quality: chosen.quality, effort: 6 }).toFile(`${stem}.avif`)
    for (const width of widths) {
      await sharp(source).resize({ width, kernel: "lanczos3" })
        .avif({ quality: chosen.quality, effort: 6 }).toFile(`${stem}-${width}w.avif`)
    }
    manifest[key] = chosen.quality
    saved += chosen.original - chosen.bytes
    console.log(`${file}: q${chosen.quality} ssim ${chosen.score.toFixed(4)} ${(chosen.original / 1024).toFixed(0)}KB -> ${(chosen.bytes / 1024).toFixed(0)}KB`)
  } finally {
    await rm(scratch, { recursive: true, force: true })
  }
}

const queue = [...sources]
await Promise.all(Array.from({ length: Math.max(1, os.cpus().length - 2) }, async () => {
  while (queue.length) await encodeSource(queue.shift())
}))

const sorted = Object.fromEntries(Object.entries(manifest).sort(([a], [b]) => a.localeCompare(b)))
await writeFile(manifestPath, manifestHeader + JSON.stringify(sorted, null, 2) + "\n")
console.log(`${Object.keys(sorted).length} sources with AVIF, ${skipped} skipped, ${(saved / 1024).toFixed(0)}KB saved at full size this run`)
